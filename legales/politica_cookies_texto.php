<h2>1. ¿Qué son las Cookies?</h2>
<p>Una cookie es un pequeño archivo que se almacena en el dispositivo del usuario y que permite recordar información
    sobre su navegación. Las cookies facilitan que la web funcione correctamente y ayudan a mejorar la experiencia del
    usuario.</p>

<h2>2. Tipos de Cookies que Utiliza este Sitio Web</h2>
<ul>
    <li><strong>Cookies técnicas:</strong> necesarias para el funcionamiento básico de la web y la prestación del
        servicio.</li>
    <li><strong>Cookies de personalización:</strong> permiten recordar las preferencias del usuario, como el idioma o el
        tipo de navegador utilizado.</li>
    <li><strong>Cookies de análisis:</strong> permiten cuantificar el número de usuarios y analizar su comportamiento
        para mejorar el sitio web.</li>
    <li><strong>Cookies de terceros (YouTube):</strong> Los vídeos incrustados de YouTube en esta web solo se cargan si
        el usuario pulsa "ver". Al hacerlo, YouTube puede instalar cookies para gestionar la reproducción, la calidad
        del vídeo y la sesión del reproductor. Estas cookies son gestionadas por YouTube y no por esta web.</li>
    <li><strong>Redes sociales:</strong> Esta web incluye enlaces a redes sociales (Facebook, Instagram, Spotify, etc.).
        Estos enlaces no instalan cookies mientras no se pulse sobre ellos. Si decides visitar la red social, sus
        propias cookies y políticas de privacidad se aplicarán en su sitio web.</li>

</ul>

<h2>3. Gestión y Eliminación de Cookies</h2>
<p>El usuario puede permitir, bloquear o eliminar las cookies instaladas en su equipo mediante la configuración del
    navegador:</p>
<ul>
    <li><strong>Google Chrome:</strong> Configuración &gt; Privacidad y seguridad &gt; Cookies y otros datos del sitio
    </li>
    <li><strong>Mozilla Firefox:</strong> Opciones &gt; Privacidad y seguridad &gt; Cookies y datos del sitio</li>
    <li><strong>Safari:</strong> Preferencias &gt; Privacidad</li>
    <li><strong>Microsoft Edge:</strong> Configuración &gt; Cookies y permisos del sitio</li>

</ul>

<h2>4. Consentimiento</h2>
<p>Al continuar navegando en este sitio web, el usuario acepta el uso de las cookies según lo indicado en esta Política.
    En cualquier momento podrá retirar su consentimiento eliminando las cookies desde la configuración de su navegador.
</p>

